export type IconName = keyof typeof ICONS;

export interface IconSvgOptions {
  /** Extra classes after "icon". */
  class?: string;
  /** Accessible name. Leave out for a decorative icon next to text (it gets aria-hidden). */
  label?: string;
}

/** A complete <svg> string. Server-side, prefer <Icon name="..." />; this is for client scripts. */
export function iconSvg(name: IconName, options: IconSvgOptions = {}): string {
  const classes = options.class ? `icon ${options.class}` : 'icon';
  const a11y = options.label
    ? `role="img" aria-label="${options.label.replace(/&/g, '&amp;').replace(/"/g, '&quot;')}"`
    : 'aria-hidden="true"';
  return (
    `<svg class="${classes}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" ${a11y}>${ICONS[name]}</svg>`
  );
}
